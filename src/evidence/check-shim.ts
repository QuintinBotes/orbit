import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { atomicWrite } from '../core/fsx.ts';
import { sha256 } from '../core/hash.ts';

/**
 * The detached process that owns one check. The controller spawns it and may
 * die; the shim keeps running, enforces the timeout itself, caps the output,
 * and writes `exit.json` atomically when the check ends, so any later
 * controller incarnation can collect the result (docs/architecture.md
 * "Process model").
 *
 * It is plain JavaScript in a string, written next to the run, so it runs
 * identically from a source checkout, a test, and the single-file bundle
 * (which has no separate shim entry for checks). It imports nothing from
 * Orbit: it must stay small enough to audit at a glance.
 *
 * The check runs in its own process group (distinct from the shim's), so the
 * shim can stop the whole tree on timeout or cancellation and still live to
 * report what happened.
 *
 * Nothing of a check may run that no record names. The shim writes
 * `registration.json` (its own identity) before it spawns the check, so a shim
 * that died without `pid.json` is known to have reached the spawn or not; it
 * gives the check the intent's token in the environment (CHECK_TOKEN_ENV),
 * where core/proc findProcessesWithEnv finds every process of the check that
 * kept it when no record names the check's group (a shim killed between the
 * spawn and `pid.json`); and when `pid.json` cannot be written after the spawn,
 * it stops the check's group before it reports the error in `exit.json`.
 */

export const SHIM_FILES = {
  intent: 'intent.json',
  launch: 'launch.json',
  registration: 'registration.json',
  pid: 'pid.json',
  exit: 'exit.json',
  output: 'output.raw',
} as const;

/** The environment variable that carries the intent's token to every process of the check. */
export const CHECK_TOKEN_ENV = 'ORBIT_CHECK_TOKEN';

/** What the controller tells the shim. Environment travels in the shim's own env, never on disk. */
export interface ShimIntent {
  token: string;
  checkRunId: string;
  argv: string[];
  cwd: string;
  timeoutMs: number;
  killGraceMs: number;
  maxOutputBytes: number;
  writtenAt: number;
}

/** Written by the controller right after spawning, to pair the pid with its start time. */
export interface ShimLaunch {
  token: string;
  pid: number;
  procStart: string | null;
}

/**
 * Written by the shim before it spawns the check: its own identity. Present without `pid.json`, the shim may have
 * spawned the check (and been killed before it could record it); absent, it never reached the spawn.
 */
export interface ShimRegistration {
  token: string;
  shimPid: number;
  registeredAt: number;
}

export interface ShimPid {
  token: string;
  shimPid: number;
  childPid: number | null;
  /** The check's own process group; equals childPid. */
  childPgid: number | null;
  startedAt: number;
}

export interface ShimExit {
  token: string;
  exitCode: number | null;
  signal: string | null;
  timedOut: boolean;
  cancelled: boolean;
  outputBytes: number;
  outputTruncated: boolean;
  endedAt: number;
  /** Set when the check could not be started at all. */
  error: string | null;
}

export const CHECK_SHIM_SOURCE = `// Generated by Orbit (evidence/check-shim.ts). Do not edit.
import { spawn } from 'node:child_process';
import { closeSync, openSync, readFileSync, renameSync, writeFileSync, writeSync } from 'node:fs';
import { join } from 'node:path';

const dir = process.argv[2];
const intent = JSON.parse(readFileSync(join(dir, 'intent.json'), 'utf8'));

function message(e) {
  return String(e && e.message ? e.message : e);
}

function put(name, value) {
  const tmp = join(dir, '.' + name + '.' + process.pid + '.tmp');
  writeFileSync(tmp, JSON.stringify(value));
  renameSync(tmp, join(dir, name));
}

const out = openSync(join(dir, 'output.raw'), 'a', 0o600);
let written = 0;
let dropped = 0;
function sink(chunk) {
  const room = intent.maxOutputBytes - written;
  if (room <= 0) { dropped += chunk.length; return; }
  const part = chunk.length <= room ? chunk : chunk.subarray(0, room);
  writeSync(out, part);
  written += part.length;
  dropped += chunk.length - part.length;
}
function note(text) {
  const b = Buffer.from(text);
  writeSync(out, b);
  written += b.length;
}

let timedOut = false;
let cancelled = false;
let stopping = false;
let finished = false;
let child = null;
let result = { exitCode: null, signal: null, error: null };
let killTimer = null;

function signalGroup(sig) {
  if (!child || child.pid === undefined) return;
  try { process.kill(-child.pid, sig); } catch (e) { /* group already gone */ }
}

function stop() {
  if (stopping) return;
  stopping = true;
  signalGroup('SIGTERM');
  killTimer = setTimeout(() => signalGroup('SIGKILL'), intent.killGraceMs);
}

function finish() {
  if (finished) return;
  finished = true;
  if (killTimer) clearTimeout(killTimer);
  clearTimeout(deadline);
  if (dropped > 0) note('\\n[orbit: output truncated: ' + dropped + ' bytes dropped after the first ' + intent.maxOutputBytes + ']\\n');
  closeSync(out);
  put('exit.json', {
    token: intent.token,
    exitCode: result.exitCode,
    signal: result.signal,
    timedOut,
    cancelled,
    outputBytes: written,
    outputTruncated: dropped > 0,
    endedAt: Date.now(),
    error: result.error,
  });
  process.exit(0);
}

const deadline = setTimeout(() => {
  timedOut = true;
  note('\\n[orbit: check timed out after ' + Math.round(intent.timeoutMs / 1000) + 's and was stopped]\\n');
  stop();
}, intent.timeoutMs);

for (const sig of ['SIGTERM', 'SIGINT', 'SIGHUP']) {
  process.on(sig, () => {
    if (!stopping) cancelled = true;
    note('\\n[orbit: check cancelled]\\n');
    stop();
  });
}

// The shim's identity before the spawn: a shim that dies before pid.json names the check is known to have reached the spawn.
try {
  put('registration.json', { token: intent.token, shimPid: process.pid, registeredAt: Date.now() });
} catch (e) {
  result.error = 'could not register the check shim: ' + message(e);
  finish();
}

try {
  child = spawn(intent.argv[0], intent.argv.slice(1), {
    cwd: intent.cwd,
    // Every process of the check inherits the token: a search of the process table finds them when no record names the group.
    env: { ...process.env, ${CHECK_TOKEN_ENV}: intent.token },
    detached: true,
    stdio: ['ignore', 'pipe', 'pipe'],
  });
} catch (e) {
  result.error = message(e);
  put('pid.json', { token: intent.token, shimPid: process.pid, childPid: null, childPgid: null, startedAt: Date.now() });
  finish();
}

if (child) {
  child.on('error', (e) => {
    result.error = message(e);
    finish();
  });
  child.stdout.on('data', sink);
  child.stderr.on('data', sink);
  if (child.pid !== undefined) {
    try {
      put('pid.json', { token: intent.token, shimPid: process.pid, childPid: child.pid, childPgid: child.pid, startedAt: Date.now() });
    } catch (e) {
      // Nothing would name the check's group: it is stopped before the shim reports, so it never runs unrecorded.
      result.error = 'could not record the check process: ' + message(e);
      signalGroup('SIGKILL');
      finish();
    }
  }
  child.on('exit', (code, signal) => {
    result.exitCode = code;
    result.signal = signal;
    // Whatever the check left running in its group (daemons, watchers) must not outlive it.
    signalGroup('SIGKILL');
    // Output may still be in flight; give the pipes a moment, but never wait for a grandchild that kept them open.
    setTimeout(finish, 300).unref();
    child.on('close', finish);
  });
}
`;

export const CHECK_SHIM_HASH = sha256(CHECK_SHIM_SOURCE);

/** Write the shim into the run directory if it is missing or different. Returns its path. */
export function ensureShim(runDir: string): string {
  const path = join(runDir, 'check-shim.mjs');
  let current: string | null = null;
  try {
    current = readFileSync(path, 'utf8');
  } catch {
    /* not written yet */
  }
  if (current !== CHECK_SHIM_SOURCE) atomicWrite(path, CHECK_SHIM_SOURCE, 0o444);
  return path;
}

export function readJsonFile<T>(path: string): T | null {
  if (!existsSync(path)) return null;
  try {
    return JSON.parse(readFileSync(path, 'utf8')) as T;
  } catch {
    // A torn read cannot happen (writes are renames), so unreadable JSON means a damaged file: treat as absent.
    return null;
  }
}

/**
 * Whether a command line (as core/proc findProcesses reads it, arguments joined by spaces) is the shim of the check in
 * `dir`. The runner starts it as `node check-shim.mjs <dir> <token>` (the shim reads only the directory; the intent's
 * token is there for this search), so a shim spawned before launch.json named it can still be found. The match is the
 * token as a whole argument, an ASCII marker no path can disturb (a random token names one attempt only); a shim
 * started before the token was added is matched by the directory its command line ends with.
 */
export function isCheckShimCommandLine(commandLine: string, dir: string, token: string): boolean {
  return (token !== '' && ` ${commandLine} `.includes(` ${token} `)) || commandLine.endsWith(` ${dir}`);
}

export function shimPath(dir: string, file: keyof typeof SHIM_FILES): string {
  return join(dir, SHIM_FILES[file]);
}
