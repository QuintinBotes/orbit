import { execFileSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { effectiveProtectedPaths } from '../../../src/policy/builtin.ts';
import { parseConfig } from '../../../src/policy/config.ts';
import { inspectScope } from '../../../src/policy/scope.ts';
import type { PolicySnapshot } from '../../../src/policy/types.ts';

const GIT_ENV = { ...process.env, GIT_CONFIG_GLOBAL: '/dev/null', GIT_CONFIG_NOSYSTEM: '1', GIT_AUTHOR_NAME: 'acme', GIT_AUTHOR_EMAIL: 'dev@acme.test', GIT_COMMITTER_NAME: 'acme', GIT_COMMITTER_EMAIL: 'dev@acme.test' };
const sh = (cwd: string, ...args: string[]) => execFileSync('git', args, { cwd, env: GIT_ENV, encoding: 'utf8' }).trim();

const config = parseConfig('version: 1\nscope: {allowed_paths: ["**"]}\nscheduler: {hard_limits: {changed_files: 10, changed_lines: 20}}\n');
const SNAPSHOT: PolicySnapshot = { schema: 'orbit.policy/1', run_id: 'orb-gen', created_at: '', repo_root: '/', config, effective_protected_paths: effectiveProtectedPaths(config), check_config_hashes: {} };

let top: string;
let n = 0;
beforeAll(() => {
  top = mkdtempSync(join(tmpdir(), 'orbit-scope-gen-'));
});
afterAll(() => rmSync(top, { recursive: true, force: true }));

function commit(repo: string, files: Record<string, string>): string {
  for (const [rel, text] of Object.entries(files)) {
    mkdirSync(dirname(join(repo, rel)), { recursive: true });
    writeFileSync(join(repo, rel), text);
  }
  sh(repo, 'add', '-A');
  sh(repo, 'commit', '-q', '-m', 'c');
  return sh(repo, 'rev-parse', 'HEAD');
}

const lines = (k: number, tag: string) => Array.from({ length: k }, (_, i) => `export const ${tag}${i} = ${i};`).join('\n') + '\n';

/** A base with a committed bundle and a candidate that changes 2 source lines and rebuilds the bundle (60 lines). */
async function bundleChange(base: Record<string, string>, cand: Record<string, string> = {}) {
  const repo = join(top, `r${(n += 1)}`);
  mkdirSync(repo);
  sh(repo, 'init', '-q', '-b', 'main');
  const baseRev = commit(repo, { 'src/a.ts': 'export const a = 1;\n', 'dist/app.mjs': lines(30, 'old'), ...base });
  const candRev = commit(repo, { 'src/a.ts': 'export const a = 2;\n', 'dist/app.mjs': lines(30, 'new'), ...cand });
  return inspectScope({ repoRoot: repo, baseRev, candidateRev: candRev, snapshot: SNAPSHOT });
}

describe('scope inspection leaves committed generated files out of the size limit (#157, #175 US1)', () => {
  it('does not count the lines of a bundle the repository marks linguist-generated', async () => {
    const r = await bundleChange({ '.gitattributes': 'dist/** linguist-generated\n' });
    expect(r.changed_lines).toBe(2);
    expect(r.generated_lines).toBe(60);
    expect(r.generated_paths).toEqual(['dist/app.mjs']);
    expect(r.changed_files).toBe(2);
    expect(r.within_size_limits).toBe(true);
  });

  it('does not count the lines of a file whose header says it is generated', async () => {
    const r = await bundleChange({ 'dist/app.mjs': `// @generated by esbuild\n${lines(30, 'old')}` }, { 'dist/app.mjs': `// @generated by esbuild\n${lines(30, 'new')}` });
    expect(r).toMatchObject({ changed_lines: 2, generated_lines: 60, within_size_limits: true });
  });

  it('counts a bundle nothing marks generated, as before', async () => {
    const r = await bundleChange({});
    expect(r.changed_lines).toBe(62);
    expect(r.generated_lines).toBeUndefined();
    expect(r.within_size_limits).toBe(false);
    expect(r.largest_changes?.[0]).toEqual({ path: 'dist/app.mjs', lines: 60 });
  });

  it('a candidate cannot mark its own change generated: the base tree must flag the file too', async () => {
    const r = await bundleChange({}, { '.gitattributes': 'dist/** linguist-generated\nsrc/** linguist-generated\n' });
    expect(r.generated_lines).toBeUndefined();
    expect(r.within_size_limits).toBe(false);
  });
});
