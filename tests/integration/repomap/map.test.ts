import { execFileSync } from 'node:child_process';
import { copyFileSync, existsSync, mkdirSync, mkdtempSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { buildRepoMap, namedPaths, promptSlice, queryRepoMap, testsCovering, type RepoMap } from '../../../src/repomap/map.ts';
import { estimateTokens } from '../../../src/knowledge/text.ts';

// No automatic maintenance: after the 5,000-file commit it would still be writing objects when the directory is removed.
const GIT_ENV = { ...process.env, GIT_CONFIG_GLOBAL: '/dev/null', GIT_CONFIG_NOSYSTEM: '1', GIT_CONFIG_COUNT: '2', GIT_CONFIG_KEY_0: 'gc.auto', GIT_CONFIG_VALUE_0: '0', GIT_CONFIG_KEY_1: 'maintenance.auto', GIT_CONFIG_VALUE_1: 'false', GIT_AUTHOR_NAME: 'acme', GIT_AUTHOR_EMAIL: 'dev@acme.test', GIT_COMMITTER_NAME: 'acme', GIT_COMMITTER_EMAIL: 'dev@acme.test' };
const sh = (cwd: string, ...args: string[]) => execFileSync('git', args, { cwd, env: GIT_ENV, encoding: 'utf8' }).trim();

let top: string;
let n = 0;
beforeAll(() => {
  top = mkdtempSync(join(tmpdir(), 'orbit-repomap-'));
});
afterAll(() => rmSync(top, { recursive: true, force: true }));

function write(repo: string, files: Record<string, string>): void {
  for (const [rel, text] of Object.entries(files)) {
    mkdirSync(dirname(join(repo, rel)), { recursive: true });
    writeFileSync(join(repo, rel), text);
  }
}

function repoWith(files: Record<string, string>): string {
  const repo = join(top, `r${(n += 1)}`);
  mkdirSync(repo);
  sh(repo, 'init', '-q', '-b', 'main');
  commit(repo, files);
  return repo;
}

function commit(repo: string, files: Record<string, string>): string {
  write(repo, files);
  sh(repo, 'add', '-A');
  sh(repo, 'commit', '-q', '--allow-empty', '-m', 'c');
  return sh(repo, 'rev-parse', 'HEAD');
}

const FIXTURE: Record<string, string> = {
  // TypeScript: ESM .js specifiers name .ts sources; a directory import names its index.
  'src/a.ts': "import { b } from './b.js';\nimport { util } from '../lib/util';\nimport fs from 'node:fs';\nexport const a = () => b() + util();\n",
  'src/b.ts': 'export const b = () => 1;\n',
  'lib/util/index.ts': 'export const util = () => 2;\n',
  'tests/a.test.ts': "import { a } from '../src/a.ts';\n",
  // Python: relative and absolute imports, a submodule named in `from pkg import mod`.
  'pkg/__init__.py': '',
  'pkg/core.py': 'from . import helpers\nimport pkg.models\n',
  'pkg/helpers.py': '',
  'pkg/models.py': '',
  'tests/test_core.py': 'from pkg.core import run\n',
  // Rust: mod declarations, crate:: paths, and an integration test using the crate by its package name.
  'crate1/Cargo.toml': '[package]\nname = "my-crate"\nversion = "0.1.0"\n',
  'crate1/src/lib.rs': 'pub mod parser;\nmod lexer;\n',
  'crate1/src/parser.rs': 'use crate::lexer::Token;\n',
  'crate1/src/lexer.rs': 'pub struct Token;\n',
  'crate1/tests/parse.rs': 'use my_crate::parser;\n',
  // Go: module-relative package imports; a _test.go file covers its package.
  'go.mod': 'module example.com/app\n\ngo 1.22\n',
  'cmd/main.go': 'package main\n\nimport (\n\t"fmt"\n\t"example.com/app/internal/store"\n)\n',
  'internal/store/store.go': 'package store\n',
  'internal/store/store_test.go': 'package store\n',
  // Ruby has no parser: file list and test mapping only.
  'lib/greeter.rb': 'class Greeter; end\n',
  'spec/greeter_spec.rb': "require 'greeter'\n",
  // Generated: by attribute, and by header.
  '.gitattributes': 'dist/** linguist-generated\n',
  'dist/bundle.mjs': "import './chunk.mjs';\n",
  'dist/chunk.mjs': '',
  'gen/api.go': '// Code generated by protoc. DO NOT EDIT.\npackage gen\n',
};

const CHECKS = { unit: { command: ['npx', 'vitest', 'run', 'tests'], cwd: '.' }, rust: { command: ['cargo test --manifest-path=crate1/Cargo.toml'], cwd: '.' }, lint: { command: ['npm', 'run', 'lint'], cwd: '.' } };

const file = (map: RepoMap, path: string) => map.files.find((f) => f.path === path)!;

describe('the repository map (#175 FR-001)', () => {
  it('lists every tracked file with its size, and the import edges of TypeScript, JavaScript, Python, Rust and Go', async () => {
    const repo = repoWith(FIXTURE);
    const map = await buildRepoMap(repo, 'HEAD', { checks: CHECKS });
    expect(map.tree).toBe(sh(repo, 'rev-parse', 'HEAD^{tree}'));
    expect(map.files.map((f) => f.path).sort()).toEqual(Object.keys(FIXTURE).sort());
    expect(file(map, 'src/b.ts').size).toBe(FIXTURE['src/b.ts']!.length);
    expect(file(map, 'src/a.ts').imports).toEqual(['lib/util/index.ts', 'src/b.ts']);
    expect(file(map, 'dist/bundle.mjs').imports).toEqual(['dist/chunk.mjs']);
    // `from . import helpers` imports the package too.
    expect(file(map, 'pkg/core.py').imports).toEqual(['pkg/__init__.py', 'pkg/helpers.py', 'pkg/models.py']);
    expect(file(map, 'tests/test_core.py').imports).toEqual(['pkg/core.py']);
    expect(file(map, 'crate1/src/lib.rs').imports).toEqual(['crate1/src/lexer.rs', 'crate1/src/parser.rs']);
    expect(file(map, 'crate1/src/parser.rs').imports).toEqual(['crate1/src/lexer.rs']);
    expect(file(map, 'crate1/tests/parse.rs').imports).toEqual(['crate1/src/parser.rs']);
    expect(file(map, 'cmd/main.go').imports).toEqual(['internal/store/store.go']);
  });

  it('links tests to the sources they cover: by import, by name, and by Go package', async () => {
    const map = await buildRepoMap(repoWith(FIXTURE), 'HEAD');
    expect(testsCovering(map, 'src/a.ts')).toEqual(['tests/a.test.ts']);
    expect(testsCovering(map, 'pkg/core.py')).toEqual(['tests/test_core.py']);
    expect(testsCovering(map, 'crate1/src/parser.rs')).toEqual(['crate1/tests/parse.rs']);
    expect(testsCovering(map, 'internal/store/store.go')).toEqual(['internal/store/store_test.go']);
    expect(testsCovering(map, 'src/b.ts')).toEqual([]);
    expect(file(map, 'tests/a.test.ts').test).toBe(true);
    expect(file(map, 'src/a.ts').test).toBe(false);
  });

  it('a language without a parser falls back to the file list and test mapping only', async () => {
    const map = await buildRepoMap(repoWith(FIXTURE), 'HEAD');
    expect(file(map, 'spec/greeter_spec.rb')).toMatchObject({ test: true, imports: [] });
    expect(file(map, 'lib/greeter.rb')).toMatchObject({ imports: [], tests: ['spec/greeter_spec.rb'] });
  });

  it('flags generated files by the linguist-generated attribute and by a generated header, and nothing else', async () => {
    const map = await buildRepoMap(repoWith(FIXTURE), 'HEAD');
    expect(map.files.filter((f) => f.generated).map((f) => f.path).sort()).toEqual(['dist/bundle.mjs', 'dist/chunk.mjs', 'gen/api.go']);
  });

  it('takes a header only from a line that declares the file generated, not from an authored comment that names a marker', async () => {
    const map = await buildRepoMap(
      repoWith({
        'src/doc.ts': '/**\n * Files with an `@generated` or\n * `DO NOT EDIT` header are skipped.\n */\nexport {};\n',
        'src/sync.ts': '// DO NOT EDIT without updating docs/list.md.\nexport {};\n',
        'gen/relay.ts': '/**\n * @generated SignedSource<<abc>>\n */\nexport {};\n',
        'gen/proto.rs': '// This file is @generated by prost-build.\npub struct A;\n',
        'gen/auto.py': '# Auto-generated file. DO NOT EDIT.\n',
        'gen/make.js': '// DO NOT EDIT: this file is generated by make.\n',
      }),
      'HEAD',
    );
    expect(map.files.filter((f) => f.generated).map((f) => f.path).sort()).toEqual(['gen/auto.py', 'gen/make.js', 'gen/proto.rs', 'gen/relay.ts']);
  });

  it('reads the attribute on a git without check-attr --source (before 2.40), and never from the user\'s attributes file', async () => {
    const repo = repoWith({ '.gitattributes': 'dist/** linguist-generated\n', 'dist/a.mjs': '', 'src/b.ts': '' });
    const bin = join(top, `oldgit${(n += 1)}`);
    mkdirSync(bin);
    const real = execFileSync('sh', ['-c', 'command -v git'], { encoding: 'utf8' }).trim();
    writeFileSync(join(bin, 'git'), `#!/bin/sh\ncase " $* " in *" check-attr --source "*) echo "error: unknown option \\\`source'" >&2; exit 129;; esac\nexec '${real}' "$@"\n`, { mode: 0o755 });
    // gitEnv's HOME is the temp directory, which other accounts can write on Linux.
    const userAttrs = join(tmpdir(), '.config', 'git', 'attributes');
    const hadUserAttrs = existsSync(userAttrs);
    if (!hadUserAttrs) write(tmpdir(), { '.config/git/attributes': 'src/** linguist-generated\n' });
    const path = process.env.PATH;
    process.env.PATH = `${bin}:${path}`;
    try {
      const map = await buildRepoMap(repo, 'HEAD');
      expect(file(map, 'dist/a.mjs').generated).toBe(true);
      expect(file(map, 'src/b.ts').generated).toBe(false);
    } finally {
      process.env.PATH = path;
      if (!hadUserAttrs) rmSync(userAttrs);
    }
  });

  it('links each check to the tracked paths its command names', async () => {
    const map = await buildRepoMap(repoWith(FIXTURE), 'HEAD', { checks: CHECKS });
    expect(map.checks).toEqual({ unit: ['tests'], rust: ['crate1/Cargo.toml'], lint: [] });
    expect(queryRepoMap(map, 'tests/a.test.ts').files[0]!.checks).toEqual(['unit']);
  });

  it('answers a query about a file or a directory, with what imports each file', async () => {
    const map = await buildRepoMap(repoWith(FIXTURE), 'HEAD');
    const q = queryRepoMap(map, './src/b.ts');
    expect(q).toMatchObject({ path: 'src/b.ts', kind: 'file' });
    expect(q.files[0]!.imported_by).toEqual(['src/a.ts']);
    expect(queryRepoMap(map, 'pkg/').files.map((f) => f.path)).toEqual(['pkg/__init__.py', 'pkg/core.py', 'pkg/helpers.py', 'pkg/models.py']);
    expect(queryRepoMap(map, 'nope.ts').kind).toBe('missing');
  });
});

describe('the map cache (#175 FR-002)', () => {
  const cacheDir = (repo: string) => join(repo, '.git', 'orbit', 'repomap');

  it('serves a built map from the cache by tree hash, and rebuilds a changed tree reading only the changed files', async () => {
    const repo = repoWith(FIXTURE);
    const first = await buildRepoMap(repo, 'HEAD');
    expect(first.build).toMatchObject({ cached: false, reused: 0 });
    expect(first.build.parsed).toBeGreaterThan(10);
    expect((await buildRepoMap(repo, 'HEAD')).build).toEqual({ cached: true, parsed: 0, reused: 0 });
    commit(repo, { 'src/b.ts': "import { util } from '../lib/util/index.ts';\nexport const b = () => util();\n" });
    const second = await buildRepoMap(repo, 'HEAD');
    expect(second.build.cached).toBe(false);
    expect(second.build.parsed).toBe(1);
    expect(second.build.reused).toBeGreaterThan(10);
    expect(file(second, 'src/b.ts').imports).toEqual(['lib/util/index.ts']);
    expect(file(second, 'src/a.ts').imports).toEqual(['lib/util/index.ts', 'src/b.ts']);
    // The older tree is still served, unchanged.
    const again = await buildRepoMap(repo, 'HEAD~1');
    expect(again.build.cached).toBe(true);
    expect(file(again, 'src/b.ts').imports).toEqual([]);
  });

  it('reads a known blob again when its new path gives it another reader', async () => {
    const repo = repoWith({ 'notes.txt': "import './dep';\n// @generated\n", 'dep.js': '' });
    await buildRepoMap(repo, 'HEAD');
    rmSync(join(repo, 'notes.txt'));
    commit(repo, { 'entry.js': "import './dep';\n// @generated\n" });
    const map = await buildRepoMap(repo, 'HEAD');
    expect(map.build.cached).toBe(false);
    expect(file(map, 'entry.js')).toMatchObject({ imports: ['dep.js'], generated: true });
  });

  it('never serves a cached map for a different tree', async () => {
    const repo = repoWith(FIXTURE);
    const a = await buildRepoMap(repo, 'HEAD');
    commit(repo, { 'src/c.ts': 'export {};\n' });
    const treeB = sh(repo, 'rev-parse', 'HEAD^{tree}');
    // A map of tree A filed under tree B's name.
    copyFileSync(join(cacheDir(repo), `${a.tree}.json`), join(cacheDir(repo), `${treeB}.json`));
    const b = await buildRepoMap(repo, 'HEAD');
    expect(b.tree).toBe(treeB);
    expect(b.build.cached).toBe(false);
    expect(b.files.map((f) => f.path)).toContain('src/c.ts');
  });

  it('builds without a cache when the git directory cannot be written', async () => {
    const repo = repoWith({ 'a.ts': "import './b';\n", 'b.ts': '' });
    mkdirSync(join(repo, '.git', 'orbit'));
    writeFileSync(cacheDir(repo), 'not a directory');
    const map = await buildRepoMap(repo, 'HEAD');
    expect(file(map, 'a.ts').imports).toEqual(['b.ts']);
    expect((await buildRepoMap(repo, 'HEAD')).build.cached).toBe(false);
  });
});

describe('the prompt slice (#175 FR-004)', () => {
  it('holds the named modules\' files, imports and tests, within the token limit', async () => {
    const map = await buildRepoMap(repoWith(FIXTURE), 'HEAD');
    const goal = 'Rework `src/a.ts` and the pkg/ module (see src/a.ts:12).';
    expect(namedPaths(map, goal)).toEqual(['src/a.ts', 'pkg']);
    const slice = promptSlice(map, goal, { tokens: 1500, minFiles: 0 })!;
    expect(slice).toContain('src/a.ts (');
    expect(slice).toContain('imports: lib/util/index.ts, src/b.ts');
    expect(slice).toContain('tests: tests/a.test.ts');
    expect(slice).toContain('pkg/core.py (');
    expect(slice).toContain('tests: tests/test_core.py');
    expect(estimateTokens(slice)).toBeLessThanOrEqual(1500);
    const small = promptSlice(map, goal, { tokens: 100, minFiles: 0 })!;
    expect(estimateTokens(small)).toBeLessThanOrEqual(100);
    expect(small).toMatch(/\[\d+ more files not shown\]/);
  });

  it('is skipped for a repository under the size threshold, and when the goal names no tracked path', async () => {
    const map = await buildRepoMap(repoWith(FIXTURE), 'HEAD');
    expect(promptSlice(map, 'Rework src/a.ts', { tokens: 1500, minFiles: map.files.length + 1 })).toBeNull();
    expect(promptSlice(map, 'Make the docs nicer', { tokens: 1500, minFiles: 0 })).toBeNull();
  });
});

describe('build time (#175 SC-003)', () => {
  it('maps a 5,000-file repository in under ten seconds', async () => {
    const repo = join(top, 'big');
    mkdirSync(repo);
    sh(repo, 'init', '-q', '-b', 'main');
    const files: Record<string, string> = {};
    for (let i = 0; i < 5000; i++) {
      const d = `pkg${i % 50}`;
      files[`${d}/m${i}.ts`] = `import { x } from './m${i % 50 === 0 ? i : i - 1}.js';\nimport { y } from '../pkg0/m0.js';\nexport const v${i} = ${i};\n${'// filler line\n'.repeat(40)}`;
    }
    write(repo, files);
    sh(repo, 'add', '-A');
    sh(repo, 'commit', '-q', '-m', 'big');
    const started = performance.now();
    const map = await buildRepoMap(repo, 'HEAD');
    const ms = performance.now() - started;
    expect(map.files).toHaveLength(5000);
    expect(map.build.parsed).toBe(5000);
    expect(readdirSync(join(repo, '.git', 'orbit', 'repomap'))).toHaveLength(1);
    expect(ms).toBeLessThan(10_000);
  }, 120_000);
});
