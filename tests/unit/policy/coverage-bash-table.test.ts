/**
 * Characterization of the static Bash classifier across the program families
 * it knows: wrappers, shells, VCS, package managers, network clients, file
 * mutators. Each row is a command line and the outcome the classifier must
 * reach, written as
 *
 *   <category> <UNPARSED|OPAQUE flags> | <per-command: category[hosts]!inc:install:ign=> | W: <via/kind/path/flags ; ...>
 *
 * "!inc" marks a command whose destinations are not all statically known, and
 * W lists every write the command would make (nullabs: target depends on run
 * time, UNK: relative to a directory the classifier lost track of).
 * The working directory does not exist, so no node_modules is ever found.
 */
const CTX = { cwd: '/nonexistent-orbit/wt', root: '/nonexistent-orbit/wt', home: '/nonexistent-orbit/home' };

function outcome(command: string): string {
  const r = classifyBash(command, CTX);
  const flags = [r.parsed ? '' : 'UNPARSED', r.opaque ? 'OPAQUE' : ''].filter(Boolean).join(',');
  const per = r.commands.map((x) => `${x.category}${x.hosts.length ? '[' + x.hosts.join(',') + ']' : ''}${x.hostsComplete ? '' : '!inc'}${x.install ? ':' + x.install : ''}${x.ignoreScripts !== null ? ':ign=' + String(x.ignoreScripts) : ''}`);
  const w = r.writes.map((x) => `${x.via}/${x.kind}/${x.path}${x.abs === null ? '/nullabs' : ''}${x.unknownDir ? '/UNK' : ''}${x.unpack ? '/unpack' : ''}${x.recursive ? '/rec' : ''}${x.glob ? '/glob' : ''}`).join(' ; ');
  return `${r.category} ${flags} | ${per.join(' , ')} | W: ${w}`;
}

